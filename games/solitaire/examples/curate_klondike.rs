//! The bounded search may skip solvable deals. Generate the catalog offline with
//! `cargo run --locked --release -p corner-table-solitaire --example curate_klondike`.

use std::collections::HashSet;

use corner_table_solitaire::{Card, DealMode, Game, Move, Place, Suit};

const CATALOG_SIZE: usize = 1024;
const VISIT_LIMIT: usize = 2_000;
const ROUTE_LIMIT: usize = 100;

fn main() {
    println!("// Generated by examples/curate_klondike.rs. Keep the V1 order for saved seeds.");
    println!("#[rustfmt::skip]");
    println!("pub(super) static DEALS_V1: [(u64, &str); {CATALOG_SIZE}] = [");
    let mut accepted = 0;
    for seed in 0.. {
        let mode = DealMode::KlondikeDrawOne;
        let game = Game::with_mode(mode, seed);
        let mut turns = Vec::new();
        let mut remaining = VISIT_LIMIT;
        if search(game, &mut turns, &mut HashSet::new(), &mut remaining, 0)
            && Game::replay(mode, seed, turns.iter().copied()).is_some_and(|game| game.won())
        {
            println!("    ({seed}, {:?}),", encode(&turns));
            accepted += 1;
            if accepted == CATALOG_SIZE {
                break;
            }
        }
    }
    println!("];");
}

struct Candidate {
    game: Game,
    action: Move,
    draws: usize,
    priority: i32,
}

fn search(
    game: Game,
    turns: &mut Vec<Move>,
    visited: &mut HashSet<[u8; 63]>,
    remaining: &mut usize,
    depth: usize,
) -> bool {
    if game.won() {
        return true;
    }
    if depth == ROUTE_LIMIT || *remaining == 0 || !visited.insert(position_key(&game)) {
        return false;
    }
    *remaining -= 1;

    let mut candidates = Vec::new();
    // Prefer exposing face-down cards or making a foundation move possible.
    // Skipping other transfers keeps this partial search small.
    for (column, pile) in game.tableau.iter().enumerate() {
        for (index, entry) in pile.iter().enumerate().filter(|(_, entry)| entry.face_up) {
            let from = Place::Tableau(column, index);
            let exposure = if index == 0 {
                18
            } else if !pile[index - 1].face_up {
                42
            } else {
                0
            };
            if index + 1 == pile.len() {
                promote(&mut candidates, &game, from, entry.card, 0, exposure);
            }
            let can_promote_parent = index > 0 && ready_for_foundation(&game, pile[index - 1].card);
            if exposure > 0 || can_promote_parent {
                move_to_tableau(&mut candidates, &game, from, entry.card, 0, exposure);
            }
        }
    }
    for (index, pile) in game.foundations.iter().enumerate() {
        if let Some(&card) = pile.last().filter(|card| card.rank > 2)
            && can_uncover(&game, card)
        {
            move_to_tableau(
                &mut candidates,
                &game,
                Place::Foundation(index),
                card,
                0,
                -30,
            );
        }
    }
    let stock_size = game.stock.len() + game.waste.len();
    let mut game = game;
    // A Draw 1 cycle can reach every waste candidate. Follow the real draws
    // here so the witness includes the stock turnover as its own move.
    for draws in 0..=stock_size {
        if let Some(&card) = game.waste.last() {
            promote(&mut candidates, &game, Place::Waste, card, draws, 0);
            if can_uncover(&game, card) {
                move_to_tableau(&mut candidates, &game, Place::Waste, card, draws, 5);
            }
        }
        if !game.play(Move::Draw) {
            break;
        }
    }
    candidates.sort_by_key(|candidate| -candidate.priority);
    for candidate in candidates {
        let before = turns.len();
        turns.extend(std::iter::repeat_n(Move::Draw, candidate.draws));
        turns.push(candidate.action);
        if search(candidate.game, turns, visited, remaining, depth + 1) {
            return true;
        }
        turns.truncate(before);
        if *remaining == 0 {
            break;
        }
    }
    false
}

fn promote(
    candidates: &mut Vec<Candidate>,
    game: &Game,
    from: Place,
    card: Card,
    draws: usize,
    exposure: i32,
) {
    let suit = card.suit as usize;
    if !ready_for_foundation(game, card) {
        return;
    }
    let safe = card.rank <= 2
        || Suit::ALL.iter().enumerate().all(|(index, other)| {
            index == suit
                || game.foundations[index].len()
                    >= usize::from(card.rank - if card.suit.red() == other.red() { 2 } else { 1 })
        });
    let priority = if safe { 100 } else { 12 } + exposure + i32::from(13 - card.rank);
    add(
        candidates,
        game,
        from,
        Place::Foundation(suit),
        draws,
        priority,
    );
}

fn ready_for_foundation(game: &Game, card: Card) -> bool {
    game.foundations[card.suit as usize].len() + 1 == usize::from(card.rank)
}

fn can_uncover(game: &Game, destination: Card) -> bool {
    game.tableau.iter().any(|pile| {
        pile.iter()
            .find(|entry| entry.face_up)
            .is_some_and(|entry| {
                entry.card.rank + 1 == destination.rank
                    && entry.card.suit.red() != destination.suit.red()
            })
    })
}

fn move_to_tableau(
    candidates: &mut Vec<Candidate>,
    game: &Game,
    from: Place,
    card: Card,
    draws: usize,
    priority: i32,
) {
    for (column, pile) in game.tableau.iter().enumerate() {
        if matches!(from, Place::Tableau(source, _) if source == column) {
            continue;
        }
        let fits = pile.last().map_or(
            card.rank == 13 && !matches!(from, Place::Tableau(_, 0)),
            |top| top.card.rank == card.rank + 1 && top.card.suit.red() != card.suit.red(),
        );
        if fits {
            add(
                candidates,
                game,
                from,
                Place::Tableau(column, 0),
                draws,
                priority,
            );
        }
    }
}

fn add(
    candidates: &mut Vec<Candidate>,
    game: &Game,
    from: Place,
    to: Place,
    draws: usize,
    priority: i32,
) {
    let mut game = game.clone();
    let action = Move::Transfer { from, to };
    if game.play(action) {
        candidates.push(Candidate {
            game,
            action,
            draws,
            priority: priority - draws as i32,
        });
    }
}

fn position_key(game: &Game) -> [u8; 63] {
    let mut columns = [0, 1, 2, 3, 4, 5, 6];
    let id = |card: Card| (card.suit as u8) * 13 + card.rank;
    // Every nonempty column starts with a different card. A column swap or a
    // rotation of the remaining Draw 1 stock leaves the same search options.
    columns
        .sort_unstable_by_key(|&column| game.tableau[column].first().map(|entry| id(entry.card)));
    let mut key = [0; 63]; // 4 foundation lengths, 7 separators, and up to 52 cards
    for (index, pile) in game.foundations.iter().enumerate() {
        key[index] = pile.len() as u8;
    }
    let mut offset = 4;
    for column in columns {
        for entry in &game.tableau[column] {
            key[offset] = id(entry.card) | if entry.face_up { 0 } else { 64 };
            offset += 1;
        }
        offset += 1;
    }
    let stock = game
        .waste
        .iter()
        .chain(game.stock.iter().rev())
        .copied()
        .map(id);
    for card in stock {
        key[offset] = card;
        offset += 1;
    }
    let stock = &mut key[offset - game.waste.len() - game.stock.len()..offset];
    if let Some((first, _)) = stock.iter().enumerate().min_by_key(|(_, card)| *card) {
        stock.rotate_left(first);
    }
    key
}

fn encode(turns: &[Move]) -> String {
    fn digit(index: usize) -> char {
        char::from_digit(index as u32, 36).unwrap()
    }

    let mut result = String::new();
    for &turn in turns {
        match turn {
            Move::Draw => result.push('.'),
            Move::Transfer { from, to } => {
                match from {
                    Place::Waste => result.push('w'),
                    Place::Tableau(column, index) => {
                        result.push(digit(column));
                        result.push(digit(index));
                    }
                    Place::Foundation(index) => result.push((b'A' + index as u8) as char),
                    _ => unreachable!(),
                }
                result.push(match to {
                    Place::Tableau(column, _) => digit(column),
                    Place::Foundation(index) => (b'a' + index as u8) as char,
                    _ => unreachable!(),
                });
            }
            _ => unreachable!(),
        }
    }
    result
}
